//! `#[wasm_bindgen]` functions that encode a call and decode its response as
//! JSON, for the TypeScript client of [`crate::typescript`].

use anyx_protocol::Schema;

use crate::names::{pascal_case, snake_case};

/// For a schema named `poentaro`: `encode_poentaro_request(calls)` and
/// `decode_poentaro_response(methods, response)`, which JavaScript sees as
/// `encodePoentaroRequest` and `decodePoentaroResponse`. The crate that
/// includes them needs `wasm-bindgen`, and `anyx-protocol` with its `json`
/// feature.
pub fn wasm(schema: &Schema) -> String {
    let name = snake_case(&schema.name);
    let pascal = pascal_case(&schema.name);
    format!(
        r#"// Generated by anyx-protocol-generate from the `{schema_name}` schema. To change it, change the schema and generate it again.

use wasm_bindgen::prelude::wasm_bindgen;

const SCHEMA_FILES: &[anyx_protocol::SchemaFile<'static>] = &[
{files}];

fn schema() -> &'static anyx_protocol::Schema {{
    static SCHEMA_READ: ::std::sync::LazyLock<anyx_protocol::Schema> =
        ::std::sync::LazyLock::new(|| anyx_protocol::Schema::parse_files(SCHEMA_FILES).expect("the generator checked the schema"));
    &SCHEMA_READ
}}

/// Writes a request from a JSON array of calls, each `{{ "method": …,
/// "arguments": […] }}` with the method's full name, such as `files/read _`.
#[wasm_bindgen(js_name = encode{pascal}Request)]
pub fn encode_{name}_request(calls: &str) -> Result<String, String> {{
    anyx_protocol::json::encode_requests_json(schema(), calls)
}}

/// Reads the response to calls of `methods`, a JSON array of full names, as
/// a JSON array of the TypeScript client's `Outcome`s.
#[wasm_bindgen(js_name = decode{pascal}Response)]
pub fn decode_{name}_response(methods: &str, response: &str) -> Result<String, String> {{
    anyx_protocol::json::decode_responses_json(schema(), methods, response)
}}
"#,
        schema_name = schema.name,
        files = crate::rust::schema_files(schema),
    )
}
